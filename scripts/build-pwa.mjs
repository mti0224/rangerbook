/* Pages packaging and derived read models. Authoritative V1/V2 inputs stay unchanged. */
import { readdir, readFile, writeFile, access } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import {buildFastData} from './build-fast-data.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
try {
  await access(path.join(root,'.pwa-disabled'));
  await writeFile(path.join(root,'sw.js'),await readFile(path.join(root,'assets/pwa/disabled-worker.js')));
  console.log('PWA disabled: packaging the rollback worker at the original URL.');
  process.exit(0);
} catch(error) { if(error.code!=='ENOENT') throw error; }
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
async function files(dir) {
  const out = [];
  for (const entry of await readdir(path.join(root, dir), {withFileTypes:true})) {
    if (entry.name.startsWith('.') || ['node_modules','backend','deploy','docs','tests','scripts'].includes(entry.name)) continue;
    const name = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await files(name)); else out.push(name);
  }
  return out.sort();
}
execFileSync('python3',[path.join(root,'scripts/format-res-json.py'),path.join(root,'res')],{stdio:'inherit'});
console.log('Fast data',await buildFastData(root));
const all = await files('');
const record = async names => Object.fromEntries(await Promise.all(names.map(async name => {
  const bytes = await readFile(path.join(root,name));
  return [name,{hash:hash(bytes),size:bytes.length}];
})));
const data = await record(all.filter(x => x.startsWith('res/v2/') && x.endsWith('.json')));
const dataVersion = hash(JSON.stringify(data));
const metadata = JSON.stringify({schemaVersion:1,dataVersion,files:data})+'\n';
await writeFile(path.join(root,'pwa-data.json'),metadata);
const core = await record([...all.filter(x => x.endsWith('.html') ||
  /^(?:assets\/(?:js|css|locales|pwa|main_icon|setting_icon)\/|v2\/)/.test(x) || x==='manifest.webmanifest' || x==='assets/data/ranger-evolution.json'), 'pwa-data.json'].filter(x=>!x.endsWith('.cjs')));
const source = await readFile(path.join(root,'assets/pwa/service-worker.js'),'utf8');
// Worker policy changes also produce a new application version.
const appVersion = hash(JSON.stringify(Object.fromEntries(Object.entries(core).filter(([x])=>x!=='pwa-data.json')))+source);
const release = {appVersion,dataVersion,core,data};
const worker = '// Generated by node scripts/build-pwa.mjs. Edit assets/pwa/service-worker.js.\n'+
  source.replace('/* PWA_RELEASE */',JSON.stringify(release));
await writeFile(path.join(root,'sw.js'),worker);
console.log(`PWA app=${appVersion.slice(0,12)} data=${dataVersion.slice(0,12)} (${Object.keys(data).length} data files; no precaching of datasets)`);

